// Builds supabase/seed/seed.sql from products.js. Run: node supabase/seed/generate.mjs
import { writeFileSync } from 'node:fs';
import { products, SIZES, SPIN_FRAMES } from './products.js';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const hash = (id) => { let h = 0; for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0; return h; };

const rows = products.map((p, i) =>
  `(${q(p.id)}, ${q(p.brand)}, ${q(p.name)}, ${q(p.colorway)}, ${q(p.type)}, ${p.price}, ${p.mrp}, ${p.year}, ${p.isNew}, ${p.rating}, ${p.reviews}, ${q(p.blurb)}, ${arr(p.details)}, ${SPIN_FRAMES}, ${i})`);

const stock = [];
for (const p of products) {
  const h = hash(p.id);
  const out = [SIZES[h % SIZES.length]];
  if (h % 3 === 0) out.push(SIZES[(h >>> 4) % SIZES.length]);
  for (const s of SIZES) stock.push(`(${q(p.id)}, ${s}, ${out.includes(s) ? 0 : 2 + ((h >>> s) % 11)})`);
}

const sql = `-- Generated by generate.mjs. Starting catalogue, stock and promo code.
insert into public.products (id, brand, name, colorway, type, price, mrp, year, is_new, rating, reviews, blurb, details, spin_frames, sort_order)
values
${rows.join(',\n')}
on conflict (id) do nothing;

insert into public.inventory (product_id, size, stock)
values
${stock.join(',\n')}
on conflict (product_id, size) do nothing;

insert into public.promo_codes (code, percent) values ('LACEUP10', 10) on conflict (code) do nothing;
`;
writeFileSync(new URL('./seed.sql', import.meta.url), sql);
console.log('products', rows.length, 'stock rows', stock.length, 'bytes', sql.length);
